# ============================================================
# Theme colors
# ============================================================

COLOR_PRIMARY   = colors.HexColor("#4f46e5")
COLOR_TEXT      = colors.HexColor("#0f172a")
COLOR_MUTED     = colors.HexColor("#64748b")
COLOR_BORDER    = colors.HexColor("#cbd5e1")
COLOR_BORDER_STRONG = colors.HexColor("#1e293b")
COLOR_GIVEN_BG  = colors.HexColor("#f8fafc")
COLOR_SOLVED_BG = colors.HexColor("#fef2f2")
COLOR_SOLVED_TX = colors.HexColor("#dc2626")
COLOR_EMPTY_TX  = colors.HexColor("#cbd5e1")


# ============================================================
# Board rendering
# ============================================================

def _board_table(board, given_mask=None, cell_size=14, color_mode="mixed"):
    """
    Render a 9×9 board as a ReportLab Table.

    Args:
        board:       np.ndarray (9, 9)
        given_mask:  boolean array — True for given cells
        cell_size:   cell size in mm
        color_mode:  "mixed" — original in black, solved in red
                     "plain" — everything black
    """
    if given_mask is None:
        given_mask = board > 0

    # Build the data grid
    data = []
    for r in range(9):
        row = []
        for c in range(9):
            v = int(board[r, c])
            row.append(str(v) if v != 0 else "")
        data.append(row)

    # Convert to strings and style
    table = Table(
        data,
        colWidths=[cell_size * mm] * 9,
        rowHeights=[cell_size * mm] * 9,
    )

    # Build style commands
    style_cmds = [
        ("ALIGN",     (0, 0), (-1, -1), "CENTER"),
        ("VALIGN",    (0, 0), (-1, -1), "MIDDLE"),
        ("FONTNAME",  (0, 0), (-1, -1), "Helvetica-Bold"),
        ("FONTSIZE",  (0, 0), (-1, -1), 11),
        ("TEXTCOLOR", (0, 0), (-1, -1), COLOR_TEXT),
        # outer border
        ("BOX",       (0, 0), (-1, -1), 1.2, COLOR_BORDER_STRONG),
    ]

    # Internal grid lines
    for i in range(1, 9):
        w = 1.2 if i % 3 == 0 else 0.4
        col = COLOR_BORDER_STRONG if i % 3 == 0 else COLOR_BORDER
        style_cmds.append(("LINEBEFORE", (i, 0), (i, -1), w, col))
        style_cmds.append(("LINEABOVE",  (0, i), (-1, i), w, col))

    # Color cells (only in mixed mode)
    if color_mode == "mixed":
        for r in range(9):
            for c in range(9):
                if board[r, c] == 0:
                    continue
                if given_mask[r, c]:
                    style_cmds.append(
                        ("BACKGROUND", (c, r), (c, r), COLOR_GIVEN_BG),
                    )
                else:
                    style_cmds.append(
                        ("BACKGROUND", (c, r), (c, r), COLOR_SOLVED_BG),
                    )
                    style_cmds.append(
                        ("TEXTCOLOR", (c, r), (c, r), COLOR_SOLVED_TX),
                    )

    table.setStyle(TableStyle(style_cmds))
    return table


