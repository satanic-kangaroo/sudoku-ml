def build_solution_pdf(record_dict: dict) -> bytes:
    """
    Build a single-page PDF for one solved puzzle.

    Args:
        record_dict: dict with keys:
            board, solution, difficulty, solver_used,
            solver_time_ms, timestamp, thumbnail_png

    Returns:
        PDF file as bytes.
    """
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="Sudoku Solution",
        author="Sudoku ML",
    )

    styles = getSampleStyleSheet()
    story = []

    _add_page_header(story, styles, "Sudoku Solution")
    _add_info_block(story, record_dict, styles)
    _add_board_pair(story, record_dict, styles)
    _add_stats_block(story, record_dict, styles)
    _add_thumbnail(story, record_dict, styles)
    _add_footer(story, styles)

    doc.build(story)
    return buf.getvalue()


def build_history_pdf(records: list[dict]) -> bytes:
    """
    Build a multi-page PDF containing multiple solved puzzles.

    Args:
        records: list of record dicts (same shape as build_solution_pdf)

    Returns:
        PDF file as bytes.
    """
    if not records:
        raise ValueError("No records to export.")

    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="Sudoku ML — History",
        author="Sudoku ML",
    )

    styles = getSampleStyleSheet()
    story = []

    # --- Cover page ---
    _add_page_header(story, styles, "Sudoku ML — History")

    cover_style = ParagraphStyle(
        "Cover",
        parent=styles["Normal"],
        fontSize=12,
        textColor=COLOR_TEXT,
        leading=20,
    )
    story.append(Paragraph(
        f"<b>{len(records)}</b> solved puzzle(s) in this report.",
        cover_style,
    ))
    story.append(Paragraph(
        f"Generated on {datetime.now().strftime('%Y-%m-%d at %H:%M')}",
        cover_style,
    ))
    story.append(Spacer(1, 10 * mm))

    # Quick summary table
    summary_rows = [["#", "Difficulty", "Solver", "Time"]]
    for i, rec in enumerate(records, 1):
        diff = rec.get("difficulty", {}) or {}
        label = f"{diff.get('emoji', '')} {diff.get('label', '—')}".strip()
        solver = "DLX" if rec.get("solver_used") == "dlx" else "BT"
        ms = f"{rec.get('solver_time_ms', 0):.1f} ms"
        summary_rows.append([str(i), label, solver, ms])

    summary_tbl = Table(summary_rows, colWidths=[20 * mm, 60 * mm, 40 * mm, 40 * mm])
    summary_tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), COLOR_PRIMARY),
        ("TEXTCOLOR",  (0, 0), (-1, 0), colors.white),
        ("FONTNAME",   (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE",   (0, 0), (-1, -1), 10),
        ("ALIGN",      (0, 0), (-1, -1), "LEFT"),
        ("VALIGN",     (0, 0), (-1, -1), "MIDDLE"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING",    (0, 0), (-1, -1), 4),
        ("LINEBELOW",  (0, 0), (-1, 0), 0.6, COLOR_BORDER),
        ("LINEBELOW",  (0, 1), (-1, -2), 0.3, COLOR_BORDER),
    ]))
    story.append(summary_tbl)

    # --- Per-puzzle pages ---
    for i, rec in enumerate(records, 1):
        story.append(PageBreak())
        _add_page_header(story, styles, f"Puzzle #{i}")
        _add_info_block(story, rec, styles)
        _add_board_pair(story, rec, styles)
        _add_stats_block(story, rec, styles)

    _add_footer(story, styles)
    doc.build(story)
    return buf.getvalue()