# Single-page export
# ============================================================

def _add_page_header(story, styles, title_text):
    """Common header used on every page."""
    h1 = ParagraphStyle(
        "H1",
        parent=styles["Heading1"],
        fontSize=22,
        textColor=COLOR_PRIMARY,
        spaceAfter=4,
        alignment=TA_LEFT,
        fontName="Helvetica-Bold",
    )
    sub = ParagraphStyle(
        "Sub",
        parent=styles["Normal"],
        fontSize=10,
        textColor=COLOR_MUTED,
        spaceAfter=14,
        alignment=TA_LEFT,
    )
    story.append(Paragraph(title_text, h1))
    story.append(Paragraph("Generated by Sudoku ML", sub))


def _add_info_block(story, record, styles):
    """Metadata block: date, difficulty, solver, time."""
    label_style = ParagraphStyle(
        "Lbl",
        parent=styles["Normal"],
        fontSize=9,
        textColor=COLOR_MUTED,
        fontName="Helvetica",
    )
    value_style = ParagraphStyle(
        "Val",
        parent=styles["Normal"],
        fontSize=11,
        textColor=COLOR_TEXT,
        fontName="Helvetica-Bold",
    )

    diff = record.get("difficulty", {}) or {}
    diff_label = diff.get("label", "—")
    diff_emoji = diff.get("emoji", "🟢")

    solver_label = "DLX (Dancing Links)" if record.get("solver_used") == "dlx" \
                   else "Backtracking"
    ts = record.get("timestamp", datetime.now())
    ts_str = ts.strftime("%Y-%m-%d %H:%M")

    rows = [
        [
            Paragraph("Date",        label_style),
            Paragraph("Difficulty",  label_style),
            Paragraph("Solver",      label_style),
            Paragraph("Time",        label_style),
        ],
        [
            Paragraph(ts_str,                        value_style),
            Paragraph(f"{diff_emoji} {diff_label}",  value_style),
            Paragraph(solver_label,                  value_style),
            Paragraph(f"{record.get('solver_time_ms', 0):.2f} ms", value_style),
        ],
    ]

    t = Table(rows, colWidths=[42 * mm, 42 * mm, 56 * mm, 34 * mm])
    t.setStyle(TableStyle([
        ("VALIGN",     (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
        ("TOPPADDING",    (0, 1), (-1, 1), 2),
        ("LINEBELOW",  (0, 0), (-1, -1), 0.3, COLOR_BORDER),
    ]))
    story.append(t)
    story.append(Spacer(1, 6 * mm))


def _add_board_pair(story, record, styles):
    """Two boards side by side: original + solved."""
    board   = record.get("board")
    solution = record.get("solution")

    if board is None or solution is None:
        return

    given_mask = board > 0

    # Section labels
    sec_style = ParagraphStyle(
        "Sec",
        parent=styles["Normal"],
        fontSize=10,
        textColor=COLOR_MUTED,
        alignment=TA_CENTER,
        spaceAfter=3,
        fontName="Helvetica-Bold",
    )

    original_tbl = _board_table(board, given_mask, cell_size=11, color_mode="mixed")
    solved_tbl   = _board_table(solution, given_mask, cell_size=11, color_mode="mixed")

    left_col = Table(
        [[Paragraph("INPUT PUZZLE", sec_style)],
         [original_tbl]],
        colWidths=[100 * mm],
    )
    left_col.setStyle(TableStyle([
        ("ALIGN",  (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))

    right_col = Table(
        [[Paragraph("SOLUTION", sec_style)],
         [solved_tbl]],
        colWidths=[100 * mm],
    )
    right_col.setStyle(TableStyle([
        ("ALIGN",  (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))

    pair = Table(
        [[left_col, right_col]],
        colWidths=[105 * mm, 105 * mm],
    )
    pair.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN",  (0, 0), (-1, -1), "CENTER"),
    ]))
    story.append(pair)


def _add_stats_block(story, record, styles):
    """Small stats summary."""
    board = record.get("board")
    if board is None:
        return

    given_count = int(np.sum(board > 0))
    solved_count = 81 - given_count

    body_style = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontSize=10,
        textColor=COLOR_TEXT,
        leading=15,
    )
    head_style = ParagraphStyle(
        "Head",
        parent=styles["Normal"],
        fontSize=11,
        textColor=COLOR_TEXT,
        fontName="Helvetica-Bold",
        spaceAfter=4,
    )

    story.append(Spacer(1, 8 * mm))
    story.append(Paragraph("Summary", head_style))
    story.append(Paragraph(
        f"<b>{given_count}</b> given digits · "
        f"<b>{solved_count}</b> cells solved by the algorithm",
        body_style,
    ))


def _add_thumbnail(story, record, styles):
    """Small original image thumbnail."""
    thumb_bytes = record.get("thumbnail_png")
    if not thumb_bytes:
        return

    try:
        img = RLImage(BytesIO(thumb_bytes), width=50 * mm, height=50 * mm)
    except Exception:
        return

    story.append(Spacer(1, 6 * mm))
    head_style = ParagraphStyle(
        "Head",
        parent=styles["Normal"],
        fontSize=11,
        textColor=COLOR_TEXT,
        fontName="Helvetica-Bold",
        spaceAfter=4,
    )
    story.append(Paragraph("Source Image", head_style))
    story.append(img)


def _add_footer(story, styles):
    """Closing line at the bottom."""
    footer = ParagraphStyle(
        "Footer",
        parent=styles["Normal"],
        fontSize=8,
        textColor=COLOR_MUTED,
        alignment=TA_CENTER,
        spaceBefore=20,
    )
    story.append(Paragraph(
        "Generated by Sudoku ML · "
        "github.com/satanic-kangaroo/sudoku-ml",
        footer,
    ))


